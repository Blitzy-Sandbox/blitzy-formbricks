def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Define and parse the script's command-line arguments.

    Flags
    -----
    --repo-root
        Path to the git working tree. Used only when ``commits.jsonl``
        is absent (live-git fallback). Defaults to the current directory.
    --branch
        Git ref to walk in the live-git fallback. When omitted, the
        script prefers ``refs/remotes/origin/main`` if it exists, else
        ``HEAD``.
    --commits-jsonl
        Path to the line-delimited JSON file produced by
        ``extract_git.py``. When this file exists and is non-empty,
        the script reads from it instead of invoking ``git log``.
    --output
        Destination path for ``inflection.json``. Parent directories are
        created on demand.
    """

    p = argparse.ArgumentParser(
        description="Detect the AI-tool introduction inflection date.",
    )
    p.add_argument(
        "--repo-root",
        type=Path,
        default=Path("."),
        help="Path to the git working tree (default: %(default)s).",
    )
    p.add_argument(
        "--branch",
        default=None,
        help=(
            "Git ref used by the live-git fallback when commits.jsonl is "
            "absent (default: prefer refs/remotes/origin/main, else HEAD)."
        ),
    )
    p.add_argument(
        "--commits-jsonl",
        type=Path,
        default=Path("acceleration/data/commits.jsonl"),
        help=(
            "Path to commits.jsonl produced by extract_git.py "
            "(default: %(default)s)."
        ),
    )
    p.add_argument(
        "--output",
        type=Path,
        default=Path("acceleration/data/inflection.json"),
        help="Destination for inflection.json (default: %(default)s).",
    )
    return p.parse_args(argv)


def _resolve_live_git_ref(repo_root: Path, requested: str | None) -> str:
    """Pick the ref the live-git fallback should walk.

    Resolution order:
      1. The explicit ``--branch`` value when provided by the caller.
      2. ``refs/remotes/origin/main`` when it exists (canonical history
         on this monorepo).
      3. ``HEAD`` as the final fallback.
    """

    if requested:
        return requested
    try:
        subprocess.run(
            ["git", "rev-parse", "--verify", "refs/remotes/origin/main"],
            cwd=str(repo_root),
            capture_output=True,
            check=True,
        )
        return "refs/remotes/origin/main"
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "HEAD"


def main(argv: list[str] | None = None) -> int:
    """Run the inflection-detection pipeline.

    The function is intentionally non-fatal: even when no signal is
    detected, it writes an Insufficient-signal payload to the output
    path and exits ``0``. The orchestrator inspects the JSON contents to
    decide whether to continue or to short-circuit.

    Parameters
    ----------
    argv
        Command-line arguments excluding the program name. ``None`` (the
        default) reads :data:`sys.argv`.

    Returns
    -------
    int
        Process exit code. ``0`` on success (including the
        "Insufficient signal" branch); ``1`` if an unexpected I/O error
        prevents writing the output file.
    """

    args = parse_args(argv)

    # Deferred import of the structured logger so the script can still
    # run on a path where the `acceleration` package is not yet importable.
    # AAP Rule 1 (Observability) mandates correlation-ID-tagged JSON logs;
    # the fallback is stdlib logging so the operator still sees output.
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
        from acceleration.observability.logger import (  # noqa: WPS433
            generate_run_id,
            get_logger,
        )

        run_id = os.environ.get("ACCEL_RUN_ID") or generate_run_id()
        log = get_logger("acceleration.scripts.detect_inflection", run_id=run_id)
    except Exception:  # pragma: no cover - exercised only on broken installs
        import logging

        logging.basicConfig(
            level=os.environ.get("ACCEL_LOG_LEVEL", "INFO"),
            format="%(asctime)s %(levelname)s %(name)s %(message)s",
        )
        log = logging.getLogger("acceleration.scripts.detect_inflection")

    # ------------------------------------------------------------------
    # Phase 1: choose the data source.
    # ------------------------------------------------------------------
    if args.commits_jsonl.exists() and args.commits_jsonl.stat().st_size > 0:
        log.info(
            "Loading commits from %s",
            args.commits_jsonl,
            extra={"source": "jsonl", "path": str(args.commits_jsonl)},
        )
        commits = list(iter_commits_from_jsonl(args.commits_jsonl))
    else:
        ref = _resolve_live_git_ref(args.repo_root, args.branch)
        log.info(
            "commits.jsonl absent; falling back to live `git log` on ref=%s",
            ref,
            extra={"source": "git", "ref": ref, "repo_root": str(args.repo_root)},
        )
        commits = list(iter_commits_from_git(args.repo_root, ref))

    # ------------------------------------------------------------------
    # Phase 2: handle the empty-history edge case.
    # ------------------------------------------------------------------
    if not commits:
        result: dict[str, Any] = {
            "found": False,
            "value": "Insufficient signal — no commits available",
            "method": None,
            "candidates": {"A": None, "B": None},
            "needed": (
                "A populated git history or commits.jsonl produced by "
                "extract_git.py."
            ),
        }
        try:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(
                json.dumps(result, indent=2, default=str),
                encoding="utf-8",
            )
        except OSError as exc:
            log.error(
                "Failed to write output: %s",
                exc,
                extra={"output_path": str(args.output)},
            )
            return 1
        log.warning(
            "No commits available; wrote Insufficient-signal result.",
            extra={"output_path": str(args.output)},
        )
        return 0

    # ------------------------------------------------------------------
    # Phase 3: compute candidates and select.
    # ------------------------------------------------------------------
    log.info(
        "Loaded %d commits; computing candidates.",
        len(commits),
        extra={"commit_count": len(commits)},
    )
    cand_a = find_candidate_a(commits)
    counts = daily_commit_counts(commits)
    series = rolling_velocity_series(counts)
    cand_b = find_candidate_b(series)
    log.info(
        "Candidate A: %s",
        cand_a["date"] if cand_a else "none",
        extra={"candidate": "A", "date": cand_a["date"] if cand_a else None},
    )
    log.info(
        "Candidate B: %s",
        cand_b["date"] if cand_b else "none",
        extra={"candidate": "B", "date": cand_b["date"] if cand_b else None},
    )

    result = select_inflection(cand_a, cand_b)

    # Attach summary statistics about the velocity series so the
    # Methodology section of the report can describe the data envelope
    # the algorithm was operating over.
    result["velocity_series_summary"] = {
        "window_days": ROLLING_WINDOW_DAYS,
        "window_count": len(series),
        "first_window": series[0][0].isoformat() if series else None,
        "last_window": series[-1][0].isoformat() if series else None,
        "max_window_count": max((s[1] for s in series), default=0),
    }
    result["params"] = {
        "rolling_window_days": ROLLING_WINDOW_DAYS,
        "inflection_sigma": INFLECTION_SIGMA,
        "min_run_windows": INFLECTION_MIN_RUN_WINDOWS,
        "convergence_horizon_days": CONVERGENCE_HORIZON_DAYS,
    }

    # ------------------------------------------------------------------
    # Phase 4: persist the result.
    # ------------------------------------------------------------------
    try:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(
            json.dumps(result, indent=2, default=str),
            encoding="utf-8",
        )
    except OSError as exc:
        log.error(
            "Failed to write output: %s",
            exc,
            extra={"output_path": str(args.output)},
        )
        return 1

    if result["found"]:
        log.info(
            "Inflection date: %s  method=%s",
            result["date"],
            result["method"],
            extra={
                "inflection_date": result["date"],
                "method": result["method"],
                "chosen_candidate": result.get("chosen_candidate"),
                "output_path": str(args.output),
            },
        )
    else:
        log.warning(
            result["value"],
            extra={"output_path": str(args.output)},
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())

