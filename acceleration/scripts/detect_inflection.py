# Candidate B: sharpest sustained velocity inflection
# ---------------------------------------------------------------------------


def monday_floor(d: date) -> date:
    """Return the most recent Monday on or before ``d``.

    Python's :meth:`date.weekday` returns 0 for Monday, so subtracting
    that value gives the Monday of the same ISO week.
    """

    return d - timedelta(days=d.weekday())


def bucket_to_window_start(d: date) -> date:
    """Return the start date of the 14-day Monday-aligned window containing ``d``.

    The windowing is anchored at ``2000-01-03`` (a Monday) so that two
    machines running the analysis at different times produce bit-identical
    window assignments for any given commit. Without an anchor, the
    window grid would shift with the head-date.

    Walking through the math: take the Monday of ``d``'s week, compute its
    distance in days from the epoch Monday, then subtract whatever portion
    of that distance is "into" the current 14-day window (the modulo).
    """

    md = monday_floor(d)
    epoch = date(2000, 1, 3)  # Monday immediately following the Year 2000 weekend
    days_since = (md - epoch).days
    return md - timedelta(days=days_since % ROLLING_WINDOW_DAYS)


def daily_commit_counts(commits: Iterable[Commit]) -> dict[date, int]:
    """Aggregate commits by their author-timestamp UTC calendar date.

    The author date (not the committer date) is used so that rebases and
    cherry-picks land on the same day they were originally written; this
    is the date that human readers associate with the work being done.
    """

    counts: dict[date, int] = {}
    for c in commits:
        d = c.author_dt().date()
        counts[d] = counts.get(d, 0) + 1
    return counts


def rolling_velocity_series(counts: dict[date, int]) -> list[tuple[date, int]]:
    """Return non-overlapping 14-day buckets across the observed range.

    The series is built across the closed interval [min observed date,
    max observed date] in :data:`ROLLING_WINDOW_DAYS` steps, with each
    bucket's count being the sum of daily commit counts within the
    14-day span. Buckets with no commits are kept (count 0) so the
    inflection algorithm sees a uniform time axis.

    Parameters
    ----------
    counts
        Mapping from calendar date to commit count, as produced by
        :func:`daily_commit_counts`.

    Returns
    -------
    list[tuple[date, int]]
        ``[(window_start, count_in_window), ...]`` in chronological
        order. Empty when ``counts`` is empty.
    """

    if not counts:
        return []
    sorted_dates = sorted(counts.keys())
    start = sorted_dates[0]
    end = sorted_dates[-1]
    series: list[tuple[date, int]] = []
    cur = bucket_to_window_start(start)
    while cur <= end:
        total = 0
        for offset in range(ROLLING_WINDOW_DAYS):
            d = cur + timedelta(days=offset)
            total += counts.get(d, 0)
        series.append((cur, total))
        cur += timedelta(days=ROLLING_WINDOW_DAYS)
    return series


def find_candidate_b(series: list[tuple[date, int]]) -> dict[str, Any] | None:
    """Find the sharpest sustained inflection in a velocity series.

    Algorithm (AAP section 0.3.1.2):
      For each candidate window index ``i``:
        1. Compute the *prefix* mean and sample standard deviation over
           ``series[:i]`` (i.e. windows *before* the candidate). Using
           the prefix prevents the inflection itself from inflating
           ``sigma`` and thereby hiding itself.
        2. Form the threshold ``prefix_mean + INFLECTION_SIGMA * prefix_std``.
        3. Check whether all windows in ``series[i : i + MIN_RUN_WINDOWS]``
           exceed the threshold (the "sustained" requirement).
        4. If yes, record the candidate with a "sharpness" score equal to
           the median window count over the sustained run; higher score
           wins.

    Sample-variance Bessel correction (``/ (n-1)``) is used because the
    prefix is a sample of the broader pre-introduction population, not
    the population itself. With only two prefix windows, the divisor is
    one (``max(n-1, 1)``) which yields the squared deviation - the
    correct two-sample variance.

    Returns
    -------
    dict[str, Any] | None
        The strongest candidate (highest median run-count, earliest index
        on ties), or ``None`` when no sustained inflection passes the
        threshold or when there are not enough windows to evaluate at all.
    """

    # Need >= MIN_RUN windows to satisfy the run-length test, AND >= 2
    # windows of prefix for sample variance, so >= MIN_RUN + 2 in total.
    if len(series) < INFLECTION_MIN_RUN_WINDOWS + 2:
        return None

    candidates: list[tuple[int, float, float]] = []  # (index, score, prefix_std)
    for i in range(2, len(series) - INFLECTION_MIN_RUN_WINDOWS + 1):
        prefix = [s[1] for s in series[:i]]
        prefix_mean = sum(prefix) / len(prefix)
        # Sample variance with Bessel correction; clamp the divisor to 1
        # so it never becomes zero (only relevant defensively because the
        # i>=2 loop guard already ensures len(prefix) >= 2).
        prefix_var = sum((x - prefix_mean) ** 2 for x in prefix) / max(
            len(prefix) - 1, 1
        )
        prefix_std = math.sqrt(prefix_var)
        threshold = prefix_mean + INFLECTION_SIGMA * prefix_std
        window_slice = series[i : i + INFLECTION_MIN_RUN_WINDOWS]
        if all(w[1] > threshold for w in window_slice):
            # "Sharpest" tie-break: median count over the run. Median is
            # more robust than mean against a single huge spike inside an
            # otherwise modest run.
            sorted_counts = sorted(w[1] for w in window_slice)
            score = sorted_counts[len(sorted_counts) // 2]
            candidates.append((i, float(score), prefix_std))

    if not candidates:
        return None

    # Highest score wins; ties resolve to the earliest window (the first
    # window where the elevation began).
    candidates.sort(key=lambda t: (-t[1], t[0]))
    i, score, prefix_std = candidates[0]
    window_start = series[i][0]
    return {
        "candidate": "B",
        "date": window_start.isoformat(),
        "window_start_date": window_start.isoformat(),
        "window_count": series[i][1],
        "prefix_mean": sum(s[1] for s in series[:i]) / i,
        "prefix_std": prefix_std,
        "sigma_threshold": INFLECTION_SIGMA,
        "min_run_windows": INFLECTION_MIN_RUN_WINDOWS,
        "score_median_in_run": score,
        "description": "Sharpest sustained inflection in the rolling 14-day commit velocity series.",
    }



# ---------------------------------------------------------------------------
# Selection logic
# ---------------------------------------------------------------------------


def days_between(a_iso: str, b_iso: str) -> int:
    """Return the absolute number of calendar days between two ISO-8601 dates.

    Both arguments must be of the form ``YYYY-MM-DD``. Used to evaluate
    the convergence horizon between Candidates A and B.
    """

    return abs((date.fromisoformat(a_iso) - date.fromisoformat(b_iso)).days)


def select_inflection(
    cand_a: dict[str, Any] | None,
    cand_b: dict[str, Any] | None,
) -> dict[str, Any]:
    """Apply AAP section 0.3.1.2 selection rules to combine candidates.

    Decision matrix
    ---------------

    +---------------+---------------+-----------+--------------------------------+
    | Candidate A   | Candidate B   | gap days  | Outcome                        |
    +===============+===============+===========+================================+
    | None          | None          | -         | Insufficient signal            |
    +---------------+---------------+-----------+--------------------------------+
    | present       | present       | <= 14     | earlier of A/B, "convergent"   |
    +---------------+---------------+-----------+--------------------------------+
    | present       | present       | >  14     | B wins, "single_signal"        |
    +---------------+---------------+-----------+--------------------------------+
    | present       | None          | -         | A wins, "single_signal"        |
    +---------------+---------------+-----------+--------------------------------+
    | None          | present       | -         | B wins, "single_signal"        |
    +---------------+---------------+-----------+--------------------------------+

    The diverged-pair rule prefers Candidate B because the velocity
    inflection is the *data-driven* signal: a single ceremonial AI
    co-author trailer can mark a date weeks before sustained AI work
    actually begins.

    Returns
    -------
    dict[str, Any]
        The complete result object that becomes the body of
        ``inflection.json``. Always carries:

          * ``found``           - bool
          * ``method``          - ``None`` | ``"convergent_evidence"`` | ``"single_signal"``
          * ``candidates``      - both A and B verbatim (one may be ``None``)
          * ``rationale``       - human-readable reasoning (when found)
          * ``date``            - chosen date (when found)
          * ``chosen_candidate``- ``"A"`` | ``"B"`` (when found)
          * ``value`` / ``needed`` - Insufficient-signal explanation (when not found)
    """

    # Case 1: neither candidate detected -> Insufficient signal.
    if cand_a is None and cand_b is None:
        return {
            "found": False,
            "value": "Insufficient signal — no AI introduction detected",
            "method": None,
            "candidates": {"A": None, "B": None},
            "needed": (
                "Either at least one commit with an AI co-author trailer / "
                "AI author email, OR a sustained inflection in commit velocity "
                "exceeding 2 sigma for >= 3 windows."
            ),
        }

    # Case 2: both candidates detected.
    if cand_a is not None and cand_b is not None:
        gap = days_between(cand_a["date"], cand_b["date"])
        if gap <= CONVERGENCE_HORIZON_DAYS:
            # Convergent: pick the earlier of the two so we capture the
            # earliest evidence of the introduction event.
            chosen = cand_a if cand_a["date"] <= cand_b["date"] else cand_b
            return {
                "found": True,
                "date": chosen["date"],
                "method": "convergent_evidence",
                "convergence_gap_days": gap,
                "candidates": {"A": cand_a, "B": cand_b},
                "chosen_candidate": chosen["candidate"],
                "rationale": (
                    f"Candidates A ({cand_a['date']}) and B ({cand_b['date']}) "
                    f"are {gap} days apart (within the "
                    f"{CONVERGENCE_HORIZON_DAYS}-day convergence horizon); "
                    f"selected the earlier."
                ),
            }
        # Divergent pair -> Candidate B is the data-driven fallback.
        return {
            "found": True,
            "date": cand_b["date"],
            "method": "single_signal",
            "convergence_gap_days": gap,
            "candidates": {"A": cand_a, "B": cand_b},
            "chosen_candidate": "B",
            "rationale": (
                f"Candidates A ({cand_a['date']}) and B ({cand_b['date']}) "
                f"diverge by {gap} days (exceeds the "
                f"{CONVERGENCE_HORIZON_DAYS}-day convergence horizon); "
                f"selected Candidate B (data-driven) per AAP §0.3.1.2 "
                f"fallback rule."
            ),
        }

    # Case 3: only Candidate A present.
    if cand_a is not None:
        return {
            "found": True,
            "date": cand_a["date"],
            "method": "single_signal",
            "candidates": {"A": cand_a, "B": None},
            "chosen_candidate": "A",
            "rationale": "Only Candidate A (AI co-author trailer / author email) was detected.",
        }

    # Case 4: only Candidate B present.
    # The conditional branches above guarantee cand_b is not None here.
    assert cand_b is not None
    return {
        "found": True,
        "date": cand_b["date"],
        "method": "single_signal",
        "candidates": {"A": None, "B": cand_b},
        "chosen_candidate": "B",
        "rationale": "Only Candidate B (sustained velocity inflection) was detected.",
    }



