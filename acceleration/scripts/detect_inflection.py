def iter_commits_from_jsonl(path: Path) -> Iterator[Commit]:
    """Stream :class:`Commit` records from a line-delimited JSON file.

    Each non-blank line is decoded as a JSON object; the recognised keys
    are ``sha``, ``author_email``, ``author_date``, ``body``, ``trailers``,
    and ``ai_signal``. Unknown keys are ignored so this reader stays
    forward-compatible with the upstream ``extract_git.py`` schema.

    Malformed JSON lines are silently skipped; the detector remains robust
    in the face of a truncated extractor output and the line that failed
    can be diagnosed downstream via the line-count reported in the
    detector's INFO log.
    """

    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                # Tolerate partial writes from a previous interrupted
                # extraction; keep streaming the rest of the file.
                continue
            yield Commit(
                sha=rec.get("sha") or "",
                author_email=(rec.get("author_email") or "").lower(),
                author_date=rec.get("author_date") or "",
                body=rec.get("body") or "",
                trailers=list(rec.get("trailers") or []),
                ai_signal_precomputed=rec.get("ai_signal"),
            )


def iter_commits_from_git(repo_root: Path, ref: str) -> Iterator[Commit]:
    """Stream :class:`Commit` records by invoking ``git log`` directly.

    Used when ``commits.jsonl`` is unavailable so the script remains
    usable in isolation (for example, by an operator running it before
    ``extract_git.py`` has executed). Reads only -- never modifies the
    repository.

    The record separator is ASCII RS (`\\x1e`) and the unit separator is
    ASCII US (`\\x1f`); both are control characters that cannot appear
    inside commit metadata, eliminating ambiguity around bodies that
    contain newlines or angle brackets.

    Parameters
    ----------
    repo_root
        Directory in which `git` runs. Should resolve to a git working
        tree.
    ref
        The git ref to walk. Typically ``refs/remotes/origin/main`` for
        the canonical history; ``HEAD`` as a fallback.

    Yields
    ------
    Commit
        One record per commit reachable from ``ref``, in `git log` order
        (newest first). The detector consumes the iterator into a list
        so order does not matter for the algorithm.
    """

    fmt = "%H\x1f%aE\x1f%aI\x1f%b\x1f%(trailers:only,unfold)\x1e"
    proc = subprocess.Popen(
        ["git", "log", ref, f"--format={fmt}"],
        cwd=str(repo_root),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    assert proc.stdout is not None  # subprocess.PIPE -> non-None per spec
    buf = ""
    try:
        while True:
            chunk_bytes = proc.stdout.read(65536)
            if not chunk_bytes:
                break
            buf += chunk_bytes.decode("utf-8", errors="replace")
            while "\x1e" in buf:
                rec, buf = buf.split("\x1e", 1)
                # `git log` appends `\n` after each `%format` template,
                # leaving a leading newline at the start of every record
                # after the first. Strip it for clean parsing.
                rec = rec.lstrip("\n")
                if not rec:
                    continue
                # The body may itself contain newlines (multi-paragraph
                # commit messages) but cannot contain the US separator,
                # so `split("\x1f")` is unambiguous when followed by the
                # 5-field guard below.
                parts = rec.split("\x1f")
                if len(parts) < 5:
                    continue
                yield Commit(
                    sha=parts[0],
                    author_email=parts[1].lower(),
                    author_date=parts[2],
                    body=parts[3],
                    trailers=[t for t in parts[4].splitlines() if t.strip()],
                )
    finally:
        # Cleanly release both pipes and reap the child process. The
        # `wait(timeout=30)` is a safety net: `git log` always exits on
        # its own once stdout is drained, so 30 s is far beyond any
        # plausible blocking.
        try:
            proc.stdout.close()
        except Exception:  # pragma: no cover - defensive cleanup
            pass
        if proc.stderr is not None:
            try:
                proc.stderr.close()
            except Exception:  # pragma: no cover - defensive cleanup
                pass
        try:
            proc.wait(timeout=30)
        except subprocess.TimeoutExpired:  # pragma: no cover - defensive
            proc.kill()
            proc.wait()


# ---------------------------------------------------------------------------
# Candidate A: earliest commit with an AI-tool author/co-author signal
# ---------------------------------------------------------------------------


def is_ai_signal(commit: Commit) -> tuple[bool, list[str]]:
    """Return whether ``commit`` carries an AI-tool attribution and the indicators.

    The function checks three sources:
      1. ``commit.ai_signal_precomputed`` (when ``True``, short-circuits
         immediately; this honours an upstream extractor that has already
         performed the scan).
      2. ``commit.author_email`` against :data:`AI_EMAILS` (case-insensitive).
      3. The concatenation of ``commit.body`` and ``commit.trailers``
         against :data:`AI_TRAILER_RES`.

    Returns
    -------
    tuple[bool, list[str]]
        ``(True, ["author_email=...", "trailer=..."])`` when at least one
        signal fired; ``(False, [])`` otherwise. The indicator strings are
        truncated to 120 characters for the inflection-output payload.
    """

    if commit.ai_signal_precomputed is True:
        return True, ["precomputed_from_jsonl"]

    indicators: list[str] = []
    if commit.author_email.lower() in AI_EMAILS:
        indicators.append(f"author_email={commit.author_email}")

    # Concatenate body and trailers into a single haystack so a co-author
    # trailer that landed in either place (some git versions split them)
    # still matches. The newline join preserves line-anchored semantics
    # for the regexes (which expect "Co-authored-by:" at the start of a
    # line).
    text = "\n".join([commit.body] + commit.trailers)
    for pat in AI_TRAILER_RES:
        m = pat.search(text)
        if m:
            indicators.append(f"trailer={m.group(0)[:120]}")

    return bool(indicators), indicators


def find_candidate_a(commits: Iterable[Commit]) -> dict[str, Any] | None:
    """Find the earliest commit carrying an AI co-author/author signal.

    Iterates ``commits`` once, tracking the earliest commit (by author
    timestamp) for which :func:`is_ai_signal` returns ``True``. Returns
    a serialisable description suitable for embedding into the inflection
    JSON output.

    Returns
    -------
    dict[str, Any] | None
        A payload describing Candidate A, or ``None`` when no commit in
        ``commits`` matches any AI pattern.
    """

    earliest: tuple[datetime, Commit, list[str]] | None = None
    for c in commits:
        ok, indicators = is_ai_signal(c)
        if not ok:
            continue
        dt = c.author_dt()
        if earliest is None or dt < earliest[0]:
            earliest = (dt, c, indicators)

    if earliest is None:
        return None

    dt, c, indicators = earliest
    # `asdict(c)` produces a flat dictionary that the downstream renderers
    # can echo verbatim into the report's Methodology section. This gives
    # complete provenance for the chosen Candidate A commit, satisfying
    # the Reproducibility rule (every number traceable to a raw record).
    return {
        "candidate": "A",
        "date": dt.date().isoformat(),
        "datetime": dt.isoformat(),
        "commit_sha": c.sha,
        "author_email": c.author_email,
        "indicators": indicators,
        "commit_record": asdict(c),
        "description": "Earliest commit with AI co-author trailer or AI author email.",
    }



