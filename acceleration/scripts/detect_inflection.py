#!/usr/bin/env python3
"""
detect_inflection.py - Deterministic detection of the AI-tool introduction date.

Writes:
  acceleration/data/inflection.json

Two-candidate algorithm:
  Candidate A: earliest commit with an AI-tool author/co-author trailer.
  Candidate B: sharpest sustained inflection in a rolling 14-day commit-velocity
               series (delta > mean + 2 sigma persisting for >= 3 consecutive
               windows, with the threshold computed from the *prefix* of the
               series so the inflection itself does not contaminate it).

Selection (AAP section 0.3.1.2):
  - Both present AND within 14 days -> choose earlier; method="convergent_evidence"
  - Both present AND farther apart   -> choose Candidate B;  method="single_signal"
  - Only A present                    -> choose A;          method="single_signal"
  - Only B present                    -> choose B;          method="single_signal"
  - Neither present                   -> Insufficient signal

Authority:
  - AAP section 0.3.1   - "build a `detect_inflection` routine that scans every
                         commit's trailers for AI-tool email patterns and, in
                         parallel, computes a rolling 2-week velocity series
                         and identifies the sharpest sustained inflection."
  - AAP section 0.3.1.2 - Inflection Detection Decision Flow.
  - AAP section 0.4.1   - enumerates this file as a CREATE target.

Read-only discipline:
  - No git write operations (no `git add`, `git commit`, `git push`, branch
    creation, or remote write).
  - Filesystem writes confined to a single output file (`inflection.json`).
  - Input reads from either `commits.jsonl` (read-only) or `git log` subprocess
    (read-only).

Invocation:
  python3 acceleration/scripts/detect_inflection.py \\
      --repo-root . \\
      --branch refs/remotes/origin/main \\
      --commits-jsonl acceleration/data/commits.jsonl \\
      --output acceleration/data/inflection.json
"""

